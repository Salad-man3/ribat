import { z } from 'zod';
import {
  e164Phone,
  ianaTimeZone,
  isoDateTime,
  latitude,
  longitude,
  requiredName,
  setupCode,
  uuid,
} from './fields.js';
import { AssignableStaffPermissionsSchema } from './permissions.js';
import { S1PermissionSchema } from './s1-permission.js';

/** Named presets in the `adhan` JavaScript `CalculationMethod`. */
export const PrayerMethodSchema = z.enum([
  'MuslimWorldLeague',
  'Egyptian',
  'Karachi',
  'UmmAlQura',
  'Dubai',
  'MoonsightingCommittee',
  'NorthAmerica',
  'Kuwait',
  'Qatar',
  'Singapore',
  'Tehran',
  'Turkey',
]);
export type PrayerMethod = z.infer<typeof PrayerMethodSchema>;

export const LocaleSchema = z.enum(['ar', 'en']);

export const PrayerNameSchema = z.enum([
  'fajr',
  'sunrise',
  'dhuhr',
  'asr',
  'maghrib',
  'isha',
]);

const offsetMinutes = z.number().int().gte(-180).lte(180);

export const PrayerOffsetsSchema = z.object({
  fajr: offsetMinutes.optional(),
  sunrise: offsetMinutes.optional(),
  dhuhr: offsetMinutes.optional(),
  asr: offsetMinutes.optional(),
  maghrib: offsetMinutes.optional(),
  isha: offsetMinutes.optional(),
});
export type PrayerOffsets = z.infer<typeof PrayerOffsetsSchema>;

export const OrganizationStatusSchema = z.enum(['ACTIVE', 'SUSPENDED']);

const sheikhSchema = z.object({
  firstName: requiredName,
  fatherName: requiredName,
  familyName: requiredName,
  phone: e164Phone,
});

/**
 * WF-01, both deploy modes. Slug is generated by the server.
 * `memberLimit` is the hosted plan cap; self-host omits it.
 */
export const SetupOrganizationSchema = z.object({
  name: requiredName,
  timezone: ianaTimeZone,
  latitude,
  longitude,
  prayerMethod: PrayerMethodSchema,
  locale: LocaleSchema,
  sheikh: sheikhSchema,
  prayerOffsets: PrayerOffsetsSchema.optional(),
  memberLimit: z.number().int().positive().optional(),
});
export type SetupOrganizationInput = z.infer<typeof SetupOrganizationSchema>;

export const SetupStatusSchema = z.object({
  setupRequired: z.boolean(),
});
export type SetupStatus = z.infer<typeof SetupStatusSchema>;

/** The only organization response that contains a secret. Do not log it. */
export const SetupOrganizationResponseSchema = z.object({
  organizationId: uuid,
  sheikhMemberId: uuid,
  setupCode,
  setupCodeExpiresAt: isoDateTime,
});
export type SetupOrganizationResponse = z.infer<typeof SetupOrganizationResponseSchema>;

export const OrganizationResponseSchema = z.object({
  id: uuid,
  name: z.string(),
  slug: z.string(),
  status: OrganizationStatusSchema,
  timezone: z.string(),
  latitude,
  longitude,
  prayerMethod: PrayerMethodSchema,
  prayerOffsets: PrayerOffsetsSchema,
  locale: LocaleSchema,
  pointsEnabled: z.boolean(),
  tagsEnabled: z.boolean(),
  orgAdminPermissions: z.array(S1PermissionSchema),
  memberLimit: z.number().int().positive().nullable(),
  whatsappSetupTemplate: z.string().nullable(),
  createdAt: isoDateTime,
  updatedAt: isoDateTime,
});
export type OrganizationResponse = z.infer<typeof OrganizationResponseSchema>;

const whatsappSetupTemplateField = z
  .union([z.string().trim().max(1000), z.literal(''), z.null()])
  .optional()
  .transform((value) => {
    if (value === undefined) return undefined;
    if (value === '' || value === null) return null;
    return value;
  });

export const UpdateOrganizationSchema = z
  .object({
    name: requiredName.optional(),
    timezone: ianaTimeZone.optional(),
    latitude: latitude.optional(),
    longitude: longitude.optional(),
    prayerMethod: PrayerMethodSchema.optional(),
    prayerOffsets: PrayerOffsetsSchema.optional(),
    locale: LocaleSchema.optional(),
    pointsEnabled: z.boolean().optional(),
    tagsEnabled: z.boolean().optional(),
    orgAdminPermissions: AssignableStaffPermissionsSchema.optional(),
    whatsappSetupTemplate: whatsappSetupTemplateField,
  })
  .refine((value) => Object.keys(value).length > 0, {
    message: 'At least one field is required',
  })
  .superRefine((value, ctx) => {
    const template = value.whatsappSetupTemplate;
    if (template === undefined || template === null) return;
    if (!template.includes('{{code}}')) {
      ctx.addIssue({
        code: z.ZodIssueCode.custom,
        message: 'Template must include {{code}}',
        path: ['whatsappSetupTemplate'],
      });
    }
  });
export type UpdateOrganizationInput = z.infer<typeof UpdateOrganizationSchema>;